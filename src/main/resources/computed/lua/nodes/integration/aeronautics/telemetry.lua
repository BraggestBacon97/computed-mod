local node = computed.node(1, "computed:aeronautics_telemetry", "Telemetry (All Data)")

node:category("integration/aeronautics/telemetry")
node:style("source")
node:execution("tick")
node:field("face", "direction", { default = "front" })
node:field("channel", "text", { default = "telemetry", label = "Publish channel (CC)" })
node:output("present", "boolean")
node:output("name", "string")
node:output("x", "number")
node:output("y", "number")
node:output("z", "number")
node:output("vx", "number")
node:output("vy", "number")
node:output("vz", "number")
node:output("speed", "number")
node:output("distance", "number")
node:output("heading", "number")
node:output("hx", "number")
node:output("hy", "number")
node:output("hz", "number")
node:output("rx", "number")
node:output("ry", "number")
node:output("rz", "number")
node:output("wx", "number")
node:output("wy", "number")
node:output("wz", "number")
node:output("pitch", "number")
node:output("roll", "number")
node:output("source", "string")
node:on_run(function(ctx)
    local telemetry = ctx:endpoint("aeronautics:telemetry", ctx:field("face"))
    local data = telemetry:call("measure")
    ctx:output("present", data.present)
    if data.present then
        ctx:output("name", data.name)
        ctx:output("x", data.x)
        ctx:output("y", data.y)
        ctx:output("z", data.z)
        ctx:output("vx", data.vx)
        ctx:output("vy", data.vy)
        ctx:output("vz", data.vz)
        ctx:output("speed", data.speed)
        ctx:output("wx", data.wx)
        ctx:output("wy", data.wy)
        ctx:output("wz", data.wz)
        ctx:output("pitch", data.pitch)
        ctx:output("roll", data.roll)
        ctx:output("source", data.source)
        ctx:output("distance", data.distance)
        ctx:output("heading", data.heading)
        ctx:output("hx", data.hx)
        ctx:output("hy", data.hy)
        ctx:output("hz", data.hz)
        ctx:output("rx", data.rx)
        ctx:output("ry", data.ry)
        ctx:output("rz", data.rz)
    end
    local channel = ctx:field("channel")
    if channel ~= "" and not ctx:is_preview() then
        local ok = pcall(function()
            ctx:endpoint("computercraft:channel"):call("publish", channel, data)
        end)
        if not ok then
            -- CC not present: publishing is best-effort, the graph outputs still work
        end
    end
end)

return node
